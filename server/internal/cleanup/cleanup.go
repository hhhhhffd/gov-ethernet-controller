// ValidateApplyOptions performs the non-database part of the destructive-mode
// guard. The database name is checked separately after connecting.
func ValidateApplyOptions(options Options, databaseName string) error {
	if !options.Apply {
		return nil
	}
	if err := validateApplyIntent(options); err != nil {
		return err
	}
	if options.ConfirmTarget != databaseName {
		return fmt.Errorf("target database confirmation %q does not match current database %q", options.ConfirmTarget, databaseName)
	}
	lowerDatabaseName := strings.ToLower(databaseName)
	if strings.Contains(lowerDatabaseName, "production") || strings.Contains(lowerDatabaseName, "prod") || strings.Contains(lowerDatabaseName, "live") {
		return fmt.Errorf("refusing --apply against production/live-looking database name %q", databaseName)
	}
	return nil
}

func validateApplyIntent(options Options) error {
	if !options.Apply {
		return nil
	}
	if !options.ConfirmApply {
		return errors.New("--apply requires --confirm-apply")
	}
	environment := strings.ToLower(strings.TrimSpace(options.Environment))
	switch environment {
	case "local", "local-dev", "development", "dev", "test", "test-fixture", "ci", "staging":
	default:
		return fmt.Errorf("--apply requires a non-production --environment (got %q)", options.Environment)
	}
	if strings.TrimSpace(options.ConfirmTarget) == "" {
		return errors.New("--apply requires --confirm-target DATABASE")
	}
	return nil
}

func Run(ctx context.Context, options Options) (Result, error) {
	if err := validateApplyIntent(options); err != nil {
		return Result{}, err
	}
	if options.ConnectTimeout <= 0 {
		options.ConnectTimeout = 15 * time.Second
	}
	connectCtx, cancel := context.WithTimeout(ctx, options.ConnectTimeout)
	defer cancel()

	config, err := pgxpool.ParseConfig(databaseDSN(options.DatabaseURL))
	if err != nil {
		return Result{}, fmt.Errorf("parse PostgreSQL configuration: %w", err)
	}
	pool, err := pgxpool.NewWithConfig(connectCtx, config)
	if err != nil {
		return Result{}, fmt.Errorf("open PostgreSQL pool: %w", err)
	}
	defer pool.Close()
	if err := pool.Ping(connectCtx); err != nil {
		return Result{}, fmt.Errorf("PostgreSQL unavailable: %w", err)
	}

	var databaseName string
	if err := pool.QueryRow(connectCtx, "SELECT current_database()").Scan(&databaseName); err != nil {
		return Result{}, fmt.Errorf("read current database identity: %w", err)
	}
	if err := ValidateApplyOptions(options, databaseName); err != nil {
		return Result{}, err
	}

	tx, err := pool.BeginTx(ctx, pgx.TxOptions{IsoLevel: pgx.Serializable})
	if err != nil {
		return Result{}, fmt.Errorf("begin cleanup transaction: %w", err)
	}
	defer func() { _ = tx.Rollback(ctx) }()
	if _, err := tx.Exec(ctx, "SELECT pg_advisory_xact_lock(742032)"); err != nil {
		return Result{}, fmt.Errorf("acquire cleanup lock: %w", err)
	}
	if err := checkSchema(ctx, tx); err != nil {
		return Result{}, err
	}
	if err := createTargets(ctx, tx); err != nil {
		return Result{}, err
	}
	rows, err := collectReport(ctx, tx)
	if err != nil {
		return Result{}, err
	}

	result := Result{Database: databaseName, Applied: options.Apply, Rows: rows, Deleted: map[string]int64{}}
	if options.Apply {
		result.Deleted, err = deleteTargets(ctx, tx)
		if err != nil {
			return Result{}, err
		}
		if err := tx.Commit(ctx); err != nil {
			return Result{}, fmt.Errorf("commit cleanup transaction: %w", err)
		}
	}
	return result, nil
}

func databaseDSN(value string) string {
	if strings.TrimSpace(value) != "" {
		return value
	}
	return database.DefaultDSN()
}

func checkSchema(ctx context.Context, tx pgx.Tx) error {
	var version int64
	if err := tx.QueryRow(ctx, "SELECT COALESCE(MAX(version), 0) FROM schema_migrations").Scan(&version); err != nil {
		return fmt.Errorf("read schema migration state: %w", err)
	}
	if version < latestMigrationVersion {
		return fmt.Errorf("cleanup requires schema migration %d, database is at %d; migrations were not run by this tool", latestMigrationVersion, version)
	}
	return nil
}

func createTargets(ctx context.Context, tx pgx.Tx) error {
	for _, table := range []string{
		"organizations", "providers", "lines", "monitoring_points", "devices",
		"contract_versions", "line_context_versions", "threshold_policy_versions",
		"measurements", "measurement_evaluations", "measurement_verifications",
		"line_states", "line_state_events", "incidents", "incident_events",
		"situations", "situation_members", "situation_events", "situation_relations",
		"provider_cases", "provider_case_draft_generations", "notifications",
		"agent_commands", "live_verify_results", "agent_config_device_state",
		"agent_update_attempts",
	} {
		if _, err := tx.Exec(ctx, "CREATE TEMP TABLE cleanup_target_"+table+" (id text PRIMARY KEY) ON COMMIT DROP"); err != nil {
			return fmt.Errorf("create target table for %s: %w", table, err)
		}
	}

	if err := insertIDs(ctx, tx, "organizations", "SELECT id FROM organizations WHERE id = ANY($1::text[]) OR id LIKE ANY($2::text[])", demoOrganizationIDs, wildcardPatterns(syntheticTestPrefixes)); err != nil {
		return err
	}
	if err := insertIDs(ctx, tx, "providers", "SELECT id FROM providers WHERE id = ANY($1::text[]) OR id LIKE ANY($2::text[])", demoProviderIDs, wildcardPatterns(syntheticTestPrefixes)); err != nil {
		return err
	}
	if err := insertIDs(ctx, tx, "lines", "SELECT id FROM lines WHERE id = ANY($1::text[]) OR id LIKE ANY($2::text[]) OR organization_id IN (SELECT id FROM cleanup_target_organizations) OR provider_id IN (SELECT id FROM cleanup_target_providers)", demoLineIDs, wildcardPatterns(syntheticTestPrefixes)); err != nil {
		return err
	}
	if err := insertIDs(ctx, tx, "monitoring_points", "SELECT id FROM monitoring_points WHERE id = ANY($1::text[]) OR id LIKE ANY($2::text[]) OR line_id IN (SELECT id FROM cleanup_target_lines)", demoPointIDs, wildcardPatterns(syntheticTestPrefixes)); err != nil {
		return err
	}
	if err := insertIDs(ctx, tx, "devices", "SELECT id FROM devices WHERE id = ANY($1::text[]) OR id LIKE ANY($2::text[]) OR monitoring_point_id IN (SELECT id FROM cleanup_target_monitoring_points)", demoDeviceIDs, wildcardPatterns(syntheticTestPrefixes)); err != nil {
		return err
	}

	queries := []struct {
		table string
		query string
	}{
		{"contract_versions", "SELECT id::text FROM contract_versions WHERE line_id IN (SELECT id FROM cleanup_target_lines)"},
		{"line_context_versions", "SELECT id::text FROM line_context_versions WHERE line_id IN (SELECT id FROM cleanup_target_lines)"},
		{"threshold_policy_versions", "SELECT id::text FROM threshold_policy_versions WHERE (scope_type='LINE' AND scope_id IN (SELECT id FROM cleanup_target_lines)) OR (scope_type='GLOBAL' AND version=1 AND created_by='seed')"},
		{"measurements", "SELECT id::text FROM measurements WHERE device_id IN (SELECT id FROM cleanup_target_devices) OR line_id IN (SELECT id FROM cleanup_target_lines) OR monitoring_point_id IN (SELECT id FROM cleanup_target_monitoring_points)"},
		{"line_states", "SELECT line_id FROM line_states WHERE line_id IN (SELECT id FROM cleanup_target_lines)"},
		{"line_state_events", "SELECT id::text FROM line_state_events WHERE line_id IN (SELECT id FROM cleanup_target_lines)"},
		{"incidents", "SELECT id::text FROM incidents WHERE line_id IN (SELECT id FROM cleanup_target_lines) OR incident_no LIKE ANY($1::text[])"},
		{"situations", "SELECT DISTINCT s.id::text FROM situations s LEFT JOIN situation_members sm ON sm.situation_id=s.id WHERE sm.incident_id IN (SELECT id::bigint FROM cleanup_target_incidents) OR s.provider_id IN (SELECT id FROM cleanup_target_providers)"},
		{"situation_members", "SELECT format('%s:%s', situation_id, incident_id) FROM situation_members WHERE situation_id IN (SELECT id::bigint FROM cleanup_target_situations) OR incident_id IN (SELECT id::bigint FROM cleanup_target_incidents)"},
		{"situation_events", "SELECT id::text FROM situation_events WHERE situation_id IN (SELECT id::bigint FROM cleanup_target_situations)"},
		{"situation_relations", "SELECT format('%s:%s:%s', source_situation_id, target_situation_id, relation_type) FROM situation_relations WHERE source_situation_id IN (SELECT id::bigint FROM cleanup_target_situations) OR target_situation_id IN (SELECT id::bigint FROM cleanup_target_situations)"},
		{"incident_events", "SELECT id::text FROM incident_events WHERE incident_id IN (SELECT id::bigint FROM cleanup_target_incidents)"},
		{"provider_cases", "SELECT id::text FROM provider_cases WHERE incident_id IN (SELECT id::bigint FROM cleanup_target_incidents) OR line_id IN (SELECT id FROM cleanup_target_lines) OR created_by = $1 OR created_by LIKE ANY($2::text[])"},
		{"provider_case_draft_generations", "SELECT id::text FROM provider_case_draft_generations WHERE provider_case_id IN (SELECT id::bigint FROM cleanup_target_provider_cases)"},
		{"notifications", "SELECT id::text FROM notifications WHERE (source_type='INCIDENT' AND source_id IN (SELECT id::text FROM cleanup_target_incidents)) OR (source_type='PROVIDER_CASE' AND source_id IN (SELECT id::text FROM cleanup_target_provider_cases)) OR (source_type='TASK-023' AND source_id LIKE 'task-023-%' AND recipient_scope='task-023-scope')"},
		{"agent_commands", "SELECT id::text FROM agent_commands WHERE device_id IN (SELECT id FROM cleanup_target_devices) OR situation_id IN (SELECT id::bigint FROM cleanup_target_situations)"},
		{"live_verify_results", "SELECT command_id::text FROM live_verify_results WHERE command_id IN (SELECT id::bigint FROM cleanup_target_agent_commands) OR situation_id IN (SELECT id::bigint FROM cleanup_target_situations) OR measurement_id IN (SELECT id::bigint FROM cleanup_target_measurements)"},
		{"agent_config_device_state", "SELECT device_id FROM agent_config_device_state WHERE device_id IN (SELECT id FROM cleanup_target_devices)"},
		{"agent_update_attempts", "SELECT id::text FROM agent_update_attempts WHERE device_id IN (SELECT id FROM cleanup_target_devices)"},
	}
	for _, item := range queries {
		var args []any
		switch item.table {
		case "incidents":
			args = []any{wildcardPatterns(syntheticIncidentPrefixes)}
		case "provider_cases":
			args = []any{syntheticResetActor, wildcardPatterns(syntheticActorPrefixes)}
		}
		if err := insertQuery(ctx, tx, item.table, item.query, args...); err != nil {
			return err
		}
	}
	return nil
}

func insertIDs(ctx context.Context, tx pgx.Tx, table, query string, args ...any) error {
	return insertQuery(ctx, tx, table, query, args...)
}

func wildcardPatterns(prefixes []string) []string {
	patterns := make([]string, len(prefixes))
	for index, prefix := range prefixes {
		patterns[index] = prefix + "%"
	}
	return patterns
}

func insertQuery(ctx context.Context, tx pgx.Tx, table, query string, args ...any) error {
	if _, err := tx.Exec(ctx, "INSERT INTO cleanup_target_"+table+" (id) "+query, args...); err != nil {
		return fmt.Errorf("select synthetic %s: %w", table, err)
	}
	return nil
}

