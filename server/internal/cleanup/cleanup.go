func deleteTargets(ctx context.Context, tx pgx.Tx) (map[string]int64, error) {
	deleted := make(map[string]int64, len(deleteSpecs))
	for _, spec := range deleteSpecs {
		result, err := tx.Exec(ctx, spec.query)
		if err != nil {
			return nil, fmt.Errorf("delete synthetic %s: %w", spec.table, err)
		}
		deleted[spec.table] = result.RowsAffected()
	}
	return deleted, nil
}
