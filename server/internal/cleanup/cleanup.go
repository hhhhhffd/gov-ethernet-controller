func collectReport(ctx context.Context, tx pgx.Tx) ([]Row, error) {
	rows := make([]Row, 0, len(reportSpecs))
	for _, spec := range reportSpecs {
		var total, targeted int64
		if err := tx.QueryRow(ctx, "SELECT COUNT(*) FROM "+spec.table).Scan(&total); err != nil {
			return nil, fmt.Errorf("count %s: %w", spec.table, err)
		}
		if err := tx.QueryRow(ctx, "SELECT COUNT(*) FROM "+spec.table+" WHERE "+spec.targeted).Scan(&targeted); err != nil {
			return nil, fmt.Errorf("count synthetic %s: %w", spec.table, err)
		}
		rows = append(rows, Row{Table: spec.table, Total: total, Targeted: targeted, Rule: spec.rule, Depends: spec.depends})
	}
	return rows, nil
}

